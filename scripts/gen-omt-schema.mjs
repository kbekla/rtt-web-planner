#!/usr/bin/env node
// Generate schema/openmaptiles-<version>.json from the upstream OpenMapTiles layer
// definitions at a pinned commit. The output is committed; re-run only when bumping
// the pinned OMT version (which must match what the pinned Planetiler emits).
//
// usage: scripts/gen-omt-schema.mjs <path-to-extracted-openmaptiles-checkout>
import fs from 'node:fs';
import path from 'node:path';
import * as yaml from 'js-yaml';

const OMT_COMMIT = 'c33503af14926d68ea47f1ab7ca4d783ab544f37'; // tag v3.16
const root = process.argv[2];
if (!root) {
  console.error(`usage: gen-omt-schema.mjs <dir>
  fetch with: curl -sL https://codeload.github.com/openmaptiles/openmaptiles/tar.gz/${OMT_COMMIT} | tar xz`);
  process.exit(2);
}

// Upstream annotates some values, e.g. "road (default)", "ferry (DEPRECATED - use class)".
const stripAnnotation = (v) => String(v).replace(/\s*\(.*\)\s*$/, '');

const tileset = yaml.load(fs.readFileSync(path.join(root, 'openmaptiles.yaml'), 'utf8')).tileset;
const layers = {};
for (const rel of tileset.layers) {
  const layer = yaml.load(fs.readFileSync(path.join(root, rel), 'utf8')).layer;
  const fields = {};
  for (const [name, def] of Object.entries(layer.fields)) {
    const values = def && typeof def === 'object' && def.values;
    fields[name] = values
      ? { values: (Array.isArray(values) ? values : Object.keys(values)).map(stripAnnotation).sort() }
      : {};
  }
  layers[layer.id] = {
    fields,
    // Layers with a `name` field also carry name:<lang>, name:latin, name:nonlatin.
    localized_names: 'name' in fields,
  };
}

const out = {
  $comment: `Generated by scripts/gen-omt-schema.mjs from openmaptiles@${OMT_COMMIT}. Do not edit.`,
  version: tileset.version,
  source_commit: OMT_COMMIT,
  attribution: tileset.attribution,
  languages: tileset.languages,
  layers,
};
const file = new URL(`../schema/openmaptiles-${tileset.version}.json`, import.meta.url);
fs.writeFileSync(file, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${file.pathname}: ${Object.keys(layers).length} layers`);
